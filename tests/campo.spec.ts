const semEstouro=(page:Page)=>page.frameLocator('iframe').locator('.record-page main').evaluateAll(ns=>ns.every(n=>n.scrollHeight<=n.clientHeight+1));
async function salvarEReabrir(page:Page,nome:string){
 const downloading=page.waitForEvent('download');await page.getByRole('button',{name:/Salvar projeto/}).click();await (await downloading).saveAs(`test-results/${nome}.bcrel`);
 const restored=await abrirProjeto(new Uint8Array(await fs.readFile(`test-results/${nome}.bcrel`)).buffer);
 await page.getByRole('button',{name:/Todos os relatórios/}).click();await page.locator('input[accept=".bcrel"]').setInputFiles(`test-results/${nome}.bcrel`);
 return restored;
}

test('Excel: modelo e importação dos relatórios de campo',async()=>{
 const wb=new ExcelJS.Workbook();await wb.xlsx.load(await criarModeloExcel('dutos') as unknown as ExcelJS.Buffer);
 const ws=wb.getWorksheet('Pontos de limpeza')!;
 const col=(label:string)=>{let c=0;ws.getRow(1).eachCell((cell,n)=>{if(cell.text===label)c=n;});return c;};
 ws.getCell(2,col('Identificação do ponto')).value='Trecho A';ws.getCell(3,col('Identificação do ponto')).value='Trecho B';
 const image=wb.addImage({buffer:await fs.readFile(foto),extension:'png'});ws.addImage(image,{tl:{col:col('Foto depois da limpeza')-1,row:1},ext:{width:80,height:40}});
 wb.getWorksheet('Informações gerais')!.getCell(2,1).value='Obra importada';
 const atual=novoProjetoCampo('dutos');atual.conclusao='preservada';
 const result=await lerPlanilha(new Uint8Array(await wb.xlsx.writeBuffer()).buffer,atual);
 expect(result.erros).toEqual([]);expect(result.quantidade).toBe(2);expect(result.fotos).toBe(1);
 if(result.projeto.modelo!=='dutos')throw Error();
 expect(result.projeto.gerais.cliente).toBe('Obra importada');expect(result.projeto.itens[0].fotoDepois).toMatch(/^data:image\/png/);expect(result.projeto.conclusao).toBe('preservada');
 await expect(lerPlanilha(new Uint8Array(await wb.xlsx.writeBuffer()).buffer,novoProjetoCampo('visita'))).rejects.toThrow('Visita Técnica');
});
